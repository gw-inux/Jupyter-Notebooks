"""Refresh exact source-line maps without changing executable statements.

Run: python scripts/update_code_index.py [--check]

CODE MAP — refresh with python scripts/update_code_index.py
  L0025  source_files
  L0033  entries
  L0036  entries.visit
  L0053  indexed_source
  L0064  indexed_source.assemble
  L0073  combined_index
  L0082  main
END CODE MAP
"""
from pathlib import Path
import argparse
import ast
import re

ROOT=Path(__file__).resolve().parents[1]
BEGIN='CODE MAP — refresh with python scripts/update_code_index.py'
END='END CODE MAP'


def source_files():
    """Explicit application directories; ignore caches and generated artifacts."""
    files=[ROOT/'app.py',ROOT/'multipage_example.py']
    for folder in ('dispersion_lab','content','scripts','tests'):
        files.extend((ROOT/folder).glob('*.py'))
    return sorted(files)


def entries(tree):
    """Function/class definitions, with qualified nested names, in source order."""
    found=[]
    def visit(node,prefix=''):
        if isinstance(node,(ast.FunctionDef,ast.AsyncFunctionDef,ast.ClassDef)):
            name=prefix+node.name
            found.append((node.lineno,name))
            prefix=name+'.'
        for child in ast.iter_child_nodes(node):
            visit(child,prefix)
    visit(tree)
    if not found:
        for node in tree.body:
            if isinstance(node,(ast.Import,ast.ImportFrom)):continue
            if isinstance(node,ast.Expr) and isinstance(node.value,ast.Constant) and isinstance(node.value.value,str):continue
            found.append((node.lineno,'Module configuration / entry point'))
            break
    return sorted(found)


def indexed_source(source):
    tree=ast.parse(source)
    doc=ast.get_docstring(tree,clean=False) or 'Python source.'
    # Replace only the module docstring; function docstrings and code stay intact.
    doc=re.sub(r'\nCODE MAP .*?END CODE MAP\n?', '',doc,flags=re.S)
    doc=re.sub(r'\nTABLE OF CONTENTS.*?(?=\n\n|\Z)', '',doc,flags=re.S).strip()
    doc=re.sub(r'\n{3,}', '\n\n',doc)
    first=tree.body[0] if tree.body else None
    has_doc=isinstance(first,ast.Expr) and isinstance(first.value,ast.Constant) and isinstance(first.value.value,str)
    body='\n'.join(source.splitlines()[first.end_lineno if has_doc else 0:]).lstrip('\n')+'\n'
    mapping=entries(ast.parse(body))
    def assemble(rows):
        lines='\n'.join(f'  L{line:04d}  {name}' for line,name in rows)
        return '\"\"\"'+doc+'\n\n'+BEGIN+'\n'+lines+'\n'+END+'\n\"\"\"\n'+body
    # Header line count is fixed by the number of entries, not their values.
    draft=assemble(mapping)
    result=assemble(entries(ast.parse(draft)))
    return result,entries(ast.parse(result))


def combined_index(records):
    text='# Source code index\n\nGenerated by `python scripts/update_code_index.py`. Line numbers refer to this release; refresh after editing.\n'
    for path,rows in records:
        name=path.relative_to(ROOT).as_posix()
        text+=f'\n## [{name}]({name})\n\n| Line | Function or section |\n|---:|---|\n'
        text+=''.join(f'| {line} | `{label}` |\n' for line,label in rows)
    return text


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true',help='Report stale maps without writing.')
    args=parser.parse_args()
    stale=[];records=[]
    for path in source_files():
        original=path.read_text();updated,rows=indexed_source(original)
        records.append((path,rows))
        if updated!=original:
            stale.append(path.relative_to(ROOT).as_posix())
            if not args.check:path.write_text(updated)
    index=ROOT/'CODE_INDEX.md';text=combined_index(records)
    if not index.exists() or index.read_text()!=text:
        stale.append('CODE_INDEX.md')
        if not args.check:index.write_text(text)
    if args.check and stale:
        parser.exit(1,'Stale code maps: '+', '.join(stale)+'\n')
    print(f'{len(records)} Python source maps '+('checked.' if args.check else 'updated.'))


if __name__=='__main__':
    main()
